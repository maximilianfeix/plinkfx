/** Encode mono samples as a 16-bit PCM WAV file. */
export function wav(samples: Float32Array, sampleRate = 44100): Uint8Array {
  const n = samples.length,
    b = new DataView(new ArrayBuffer(44 + n * 2)),
    str = (o: number, s: string) => [...s].forEach((c, i) => b.setUint8(o + i, c.charCodeAt(0)));
  str(0, "RIFF");
  b.setUint32(4, 36 + n * 2, true);
  str(8, "WAVEfmt ");
  b.setUint32(16, 16, true);
  b.setUint16(20, 1, true);
  b.setUint16(22, 1, true);
  b.setUint32(24, sampleRate, true);
  b.setUint32(28, sampleRate * 2, true);
  b.setUint16(32, 2, true);
  b.setUint16(34, 16, true);
  str(36, "data");
  b.setUint32(40, n * 2, true);
  for (let i = 0; i < n; i++) b.setInt16(44 + i * 2, Math.round(Math.max(-1, Math.min(1, samples[i])) * 32767), true);
  return new Uint8Array(b.buffer);
}
